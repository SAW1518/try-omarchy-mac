#!/usr/bin/env bash
#
# migrate-to-omarchy.sh — brings macOS Rectangle and Alfred shortcuts to Omarchy 4
# (Try Omarchy, edge channel), sets the Latin American keyboard layout like on the
# Mac, swaps Nautilus for a themed Thunar, and sets the wallpaper from assets/.
#
# Run it INSIDE OMARCHY, not on the Mac. The Mac's shared folder ~/bypass shows up
# in Omarchy as ~/bypass:
#
#   bash ~/bypass/omarchy-mac/migrate-to-omarchy.sh             # install
#   bash ~/bypass/omarchy-mac/migrate-to-omarchy.sh --dry-run   # only print what it would add to bindings.lua
#   bash ~/bypass/omarchy-mac/migrate-to-omarchy.sh --uninstall # remove everything it installed
#
# Optional variables:
#   KB_LAYOUT=latam             keyboard layout (empty = leave the keyboard alone)
#   VAULT="/path/to/vault"      Obsidian vault
#   WIN_MODS="SUPER + SHIFT"    modifiers for the Rectangle actions (Cmd+Shift on the Mac)
#   RECT_GAP=10                 fixed gap in pixels (empty = same gaps as Hyprland's tiling)
#   WALLPAPER=/path/to/image    wallpaper (empty = leave the wallpaper alone)
#
# In Try Omarchy, ⌘ arrives as SUPER, ⌥ as ALT and ⌃ as CTRL.
#
# Taken from the Mac (Rectangle + Alfred 5 + Shimmering Obsidian workflow):
#
#   Rectangle (Cmd+Shift = SUPER+SHIFT)
#     ⌘⇧←  left half              ⌘⇧→  right half
#     ⌘⇧↑  top half               ⌘⇧↓  bottom half
#     ⌘⇧↩  maximize               ⌘⇧N  first third
#     ⌘⇧⌦  last third             ⌘⇧Help/Insert  first two thirds
#     ⌘⇧M  last two thirds
#     (Rectangle's factory ⌃⌥ shortcuts and Todo mode are not migrated)
#
#   Alfred
#     ⌘K   open Alfred            → SUPER+SPACE opens Apps: type to filter, Enter opens
#                                   (the Omarchy menu moves from SUPER+SPACE to SUPER+K)
#     ⌃V   clipboard history      → CTRL+V opens Omarchy's clipboard. Paste with SUPER+V;
#                                   CTRL+V no longer reaches apps, just like with Alfred
#     Shimmering Obsidian (o, or, on, ot, ov) → SUPER+ALT+O and SUPER+SHIFT+ALT+O
#
#   Keyboard: Latin American. Right Option acts as AltGr (@ = right Option + Q).
#   Try Omarchy sets kb_model=applealu_iso, which loads "latam Macintosh" and moves
#   keys around (? came out as _). assets/zzz-keyboard-pc.lua sets it back to pc105.

set -euo pipefail

KB_LAYOUT="${KB_LAYOUT-latam}"
VAULT="${VAULT:-$HOME/Obsidian}"
WIN_MODS="${WIN_MODS:-SUPER + SHIFT}"
RECT_GAP="${RECT_GAP:-}"
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WALLPAPER="${WALLPAPER-$PROJECT_DIR/assets/wallpaper.jpg}"
export OMARCHY_PATH="${OMARCHY_PATH:-/usr/share/omarchy}"

BIN_DIR="$HOME/.local/bin"
BINDINGS="$HOME/.config/hypr/bindings.lua"
STATE_DIR="$HOME/.local/state/migrate-to-omarchy"
KB_PREVIOUS="$STATE_DIR/previous-keyboard"
KB_MODEL_SRC="$PROJECT_DIR/assets/zzz-keyboard-pc.lua"
KB_MODEL_FILE="$HOME/.local/state/omarchy/toggles/hypr/zzz-keyboard-pc.lua"
THUNAR_TPL_SRC="$PROJECT_DIR/assets/thunar.css.tpl"
THUNAR_TPL="$HOME/.config/omarchy/themed/thunar.css.tpl"
GTK3_CSS="$HOME/.config/gtk-3.0/gtk.css"
TYPING_SETUP="$OMARCHY_PATH/default/input-methods/typing_setup.py"
MARK_BEGIN="-- >>> mac-migration (Rectangle + Alfred) >>>"
MARK_END="-- <<< mac-migration (Rectangle + Alfred) <<<"

info() { printf '\e[1;34m==>\e[0m %s\n' "$*"; }
warn() { printf '\e[1;33m!!\e[0m  %s\n' "$*" >&2; }
die()  { printf '\e[1;31mxx\e[0m  %s\n' "$*" >&2; exit 1; }

# Removes the block left by a previous run (and the blank lines that separated
# it), so the script can be run again and again.
strip_block() {
  awk -v b="$MARK_BEGIN" -v e="$MARK_END" '
    $0 == b { skip = 1; blanks = ""; next }
    $0 == e { skip = 0; next }
    skip { next }
    /^$/ { blanks = blanks "\n"; next }
    { printf "%s", blanks; blanks = ""; print }
  ' "$1"
}

lua_block() {
  cat <<EOF
$MARK_BEGIN
-- Generated by migrate-to-omarchy.sh. Run the script again to regenerate it,
-- or with "--uninstall" to remove it.

local mac_bin = os.getenv("HOME") .. "/.local/bin/"

local function rect(action)
  return mac_bin .. "rectangle " .. action
end

-- Drops whatever Omarchy had on that key and binds ours.
local function rebind(keys, description, command)
  hl.unbind(keys)
  o.bind(keys, description, command)
end

-- Rectangle. Replaces swap window, editor, music and the second browser
-- shortcut (the browser stays on SUPER+SHIFT+B).
rebind("$WIN_MODS + LEFT", "Rectangle: left half", rect("left-half"))
rebind("$WIN_MODS + RIGHT", "Rectangle: right half", rect("right-half"))
rebind("$WIN_MODS + UP", "Rectangle: top half", rect("top-half"))
rebind("$WIN_MODS + DOWN", "Rectangle: bottom half", rect("bottom-half"))
rebind("$WIN_MODS + RETURN", "Rectangle: maximize", rect("maximize"))
rebind("$WIN_MODS + N", "Rectangle: first third", rect("first-third"))
rebind("$WIN_MODS + Delete", "Rectangle: last third", rect("last-third"))
rebind("$WIN_MODS + Insert", "Rectangle: first two thirds", rect("first-two-thirds"))
rebind("$WIN_MODS + M", "Rectangle: last two thirds", rect("last-two-thirds"))

-- Alfred ⌘K: SUPER+SPACE opens Apps (type to filter, Enter opens). The Omarchy
-- menu moves to SUPER+K and the keybindings list to SUPER+SHIFT+K.
rebind("SUPER + SPACE", "Apps (was Alfred)", "omarchy-shell omarchy.dock apps")
rebind("SUPER + K", "Omarchy menu", { menu = "root" })
rebind("SUPER + SHIFT + K", "Keybindings", "omarchy-menu-keybindings")

-- Alfred ⌃V: clipboard history. Paste with SUPER+V.
rebind("CTRL + V", "Clipboard (was Alfred)", { panel = "omarchy.clipboard" })

-- Shimmering Obsidian.
rebind("SUPER + ALT + O", "Obsidian: find note", mac_bin .. "obsidian-menu search")
rebind("SUPER + SHIFT + ALT + O", "Obsidian: menu", mac_bin .. "obsidian-menu")

-- Thunar instead of Nautilus, with the same transparency and floating rules.
rebind("SUPER + SHIFT + F", "File manager", o.launch("thunar"))
rebind("SUPER + ALT + SHIFT + F", "File manager (cwd)", o.launch("sh -c 'thunar \"\$(omarchy-cmd-terminal-cwd)\"'"))
o.transparent_window("thunar")
o.window({ class = "thunar", title = "^(Open.*Files?|Open [F|f]older.*|Save.*Files?|Save.*As|Save|.*[C|c]hoose.*)" }, { tag = "+floating-window" })
$MARK_END
EOF
}

install_rectangle() {
  cat >"$BIN_DIR/rectangle" <<'EOF'
#!/usr/bin/env bash
# rectangle <action> — places the active window the way Rectangle did on macOS.
# Actions: left-half right-half top-half bottom-half maximize
#          first-third last-third first-two-thirds last-two-thirds
# The window becomes floating; SUPER+T puts it back into the tiling.

set -euo pipefail

action="${1:?usage: rectangle <action>}"
gap="${RECT_GAP:-__GAP__}"

hypr_dispatch() {
  local lua="$1"
  shift
  hyprctl dispatch "$lua" >/dev/null 2>&1 || hyprctl dispatch "$@" >/dev/null
}

window=$(hyprctl activewindow -j)
address=$(jq -r '.address // empty' <<<"$window")
[[ -n $address ]] || exit 0

read -r floating monitor_id fullscreen < <(jq -r '[.floating, .monitor, (.fullscreen // 0)] | @tsv' <<<"$window")

# Usable monitor area in logical pixels, minus the top bar (reserved).
read -r mx my mw mh < <(
  hyprctl monitors -j | jq -r --argjson id "$monitor_id" '
    first(.[] | select(.id == $id)) |
    ((.transform // 0) % 2 == 1) as $rotated |
    (.reserved // [0, 0, 0, 0]) as $r |
    [
      .x + $r[0],
      .y + $r[1],
      ((if $rotated then .height else .width end) / .scale) - $r[0] - $r[2],
      ((if $rotated then .width else .height end) / .scale) - $r[1] - $r[3]
    ] | map(floor) | @tsv
  '
)

x=0 y=0 w=$mw h=$mh
case $action in
  left-half)        w=$((mw / 2)) ;;
  right-half)       x=$((mw / 2)); w=$((mw - x)) ;;
  top-half)         h=$((mh / 2)) ;;
  bottom-half)      y=$((mh / 2)); h=$((mh - y)) ;;
  maximize)         ;;
  first-third)      w=$((mw / 3)) ;;
  last-third)       x=$((mw * 2 / 3)); w=$((mw - x)) ;;
  first-two-thirds) w=$((mw * 2 / 3)) ;;
  last-two-thirds)  x=$((mw / 3)); w=$((mw - x)) ;;
  *) echo "rectangle: unknown action: $action" >&2; exit 1 ;;
esac

# Same spacing as the tiling: gaps_out at the monitor edges, gaps_in between
# windows, plus the border (Hyprland draws it outside the window).
if [[ -n $gap ]]; then
  gap_in=$gap gap_out=$gap
else
  gap_in=$(hyprctl -j getoption general:gaps_in | jq -r '(.css // (.int|tostring) // "0") | split(" ")[0] | tonumber')
  gap_out=$(hyprctl -j getoption general:gaps_out | jq -r '(.css // (.int|tostring) // "0") | split(" ")[0] | tonumber')
fi
border=$(hyprctl -j getoption general:border_size | jq -r '.int // 0')
left=$(( x == 0 ? gap_out : gap_in ))
right=$(( x + w >= mw ? gap_out : gap_in ))
top=$(( y == 0 ? gap_out : gap_in ))
bottom=$(( y + h >= mh ? gap_out : gap_in ))
x=$((mx + x + left + border)) y=$((my + y + top + border))
w=$((w - left - right - 2 * border)) h=$((h - top - bottom - 2 * border))
target="address:$address"

# Hyprland won't move or resize a fullscreen window.
if [[ $fullscreen != 0 && $fullscreen != false ]]; then
  hypr_dispatch "hl.dsp.window.fullscreen_state({ internal = 0, client = 0 })" fullscreenstate 0 0
fi
if [[ $floating != true ]]; then
  hypr_dispatch "hl.dsp.window.float({ window = \"$target\", action = \"toggle\" })" togglefloating "$target"
fi
hypr_dispatch "hl.dsp.window.resize({ window = \"$target\", x = $w, y = $h })" resizewindowpixel "exact $w $h,$target"
hypr_dispatch "hl.dsp.window.move({ window = \"$target\", x = $x, y = $y })" movewindowpixel "exact $x $y,$target"
EOF
  sed -i "s/__GAP__/$RECT_GAP/" "$BIN_DIR/rectangle"
  chmod +x "$BIN_DIR/rectangle"
}

install_obsidian_menu() {
  {
    echo '#!/usr/bin/env bash'
    printf 'VAULT_DEFAULT=%q\n' "$VAULT"
    cat <<'EOF'
# obsidian-menu [search|recent|new|tags|vault] — a minimal Shimmering Obsidian.
# With no argument it shows a menu with every action.

set -euo pipefail

vault="${OBSIDIAN_VAULT:-$VAULT_DEFAULT}"

if [[ ! -d $vault ]]; then
  notify-send "Obsidian" "Vault not found: $vault" 2>/dev/null || true
  exit 1
fi

pick() {
  omarchy-menu-select "$1" -- --width 700 --maxheight 600
}

open_uri() {
  setsid -f xdg-open "$1" >/dev/null 2>&1
}

open_note() {
  open_uri "obsidian://open?path=$(jq -rn --arg p "$vault/$1.md" '$p | @uri')"
}

list_notes() {
  find "$vault" \( -name .obsidian -o -name .trash \) -prune -o -type f -name '*.md' -printf '%P\n' |
    sed 's/\.md$//' | sort
}

# o: find a note
search() {
  local note
  note=$(list_notes | pick "Find note") || exit 0
  open_note "$note"
}

# or: recent files (Obsidian keeps them in workspace.json)
recent() {
  local workspace="$vault/.obsidian/workspace.json" note
  [[ -f $workspace ]] || { notify-send "Obsidian" "No recent files yet" 2>/dev/null || true; exit 0; }
  note=$(jq -r '.lastOpenFiles[]? | select(endswith(".md"))' "$workspace" | sed 's/\.md$//' |
    pick "Recent") || exit 0
  open_note "$note"
}

# on: new note (subfolders work: "Projects/idea")
new() {
  local name file
  name=$(omarchy-menu-input "New note" --width 500) || exit 0
  name="${name%.md}"
  [[ -n $name ]] || exit 0
  file="$vault/$name.md"
  mkdir -p "$(dirname "$file")"
  [[ -e $file ]] || : >"$file"
  open_note "$name"
}

# ot: find by tag
tags() {
  local tag note
  tag=$(grep -rhoE --include='*.md' --exclude-dir=.obsidian --exclude-dir=.trash \
    '(^|[[:space:]])#[[:alnum:]_/-]*[[:alpha:]_/-][[:alnum:]_/-]*' "$vault" |
    sed -E 's/^[[:space:]]+//' | sort -u | pick "Tag") || exit 0
  note=$(grep -rlE --include='*.md' --exclude-dir=.obsidian --exclude-dir=.trash \
    "(^|[[:space:]])${tag}([^[:alnum:]_/-]|$)" "$vault" |
    sed -e "s|^$vault/||" -e 's/\.md$//' | sort | pick "Notes with $tag") || exit 0
  open_note "$note"
}

# ov: open the vault
vault() {
  open_uri "obsidian://open?vault=$(jq -rn --arg v "$(basename "$vault")" '$v | @uri')"
}

menu() {
  local choice
  choice=$(pick "Obsidian" <<<$'Find note\nRecent\nNew note\nTags\nOpen vault') || exit 0
  case $choice in
    "Find note") search ;;
    "Recent") recent ;;
    "New note") new ;;
    "Tags") tags ;;
    "Open vault") vault ;;
  esac
}

case "${1:-menu}" in
  search | recent | new | tags | vault | menu) "${1:-menu}" ;;
  *) echo "usage: obsidian-menu [search|recent|new|tags|vault]" >&2; exit 1 ;;
esac
EOF
  } >"$BIN_DIR/obsidian-menu"
  chmod +x "$BIN_DIR/obsidian-menu"
}

config_errors() {
  hyprctl configerrors 2>/dev/null | sed '/^[[:space:]]*$/d' || true
}

# Writes the block into bindings.lua and reloads Hyprland. If the reload brings a
# new error, puts the file back the way it was so the red error bar doesn't stay.
install_bindings() {
  local backup errors_before errors_after
  backup="$BINDINGS.bak-$(date +%Y%m%d-%H%M%S)"
  cp "$BINDINGS" "$backup"
  info "Backup of your bindings: $backup"

  errors_before=$(config_errors)
  { strip_block "$BINDINGS"; echo; lua_block; } >"$BINDINGS.tmp"
  mv "$BINDINGS.tmp" "$BINDINGS"
  hyprctl reload >/dev/null 2>&1 || true
  errors_after=$(config_errors)

  if [[ -n $errors_after && $errors_after != "$errors_before" ]]; then
    cp "$backup" "$BINDINGS"
    hyprctl reload >/dev/null 2>&1 || true
    printf '%s\n' "$errors_after" >&2
    die "Hyprland reported this error with the new bindings, so $BINDINGS was left as it was."
  fi
  info "Bindings added to $BINDINGS"
}

# Active layouts, in the format Omarchy's picker uses: "latam" or "us:intl latam".
current_layouts() {
  jq -rn \
    --argjson layout "$(hyprctl -j getoption input:kb_layout)" \
    --argjson variant "$(hyprctl -j getoption input:kb_variant)" '
    ($layout.str | split(",")) as $l | ($variant.str | split(",")) as $v |
    [range(0; $l | length) | $l[.] + (if ($v[.] // "") != "" then ":" + $v[.] else "" end)] |
    join(" ")'
}

# Applies layouts with the same code as Setup > Typing > Keyboard Layouts: saves
# ~/.config/omarchy/keyboard-layouts, reloads Hyprland, updates Fcitx5 and rolls
# everything back if something fails.
apply_layouts() {
  local context values
  context=$(jq -cn '{catalog: ($ARGS.positional | map({(.): .}) | add), overrides: {}}' --args "$@")
  values=$(jq -cn '$ARGS.positional' --args "$@")
  /usr/bin/python3 "$TYPING_SETUP" apply keyboard "$context" "$values" >/dev/null
}

setup_keyboard() {
  [[ -n $KB_LAYOUT ]] || return 0

  local before error=""
  local -a wanted
  read -r -a wanted <<<"$KB_LAYOUT"
  before=$(current_layouts)
  if [[ $before == "${wanted[*]}" ]]; then
    info "Keyboard is already ${wanted[*]}"
    return 0
  fi

  mkdir -p "$STATE_DIR"
  [[ -f $KB_PREVIOUS ]] || printf '%s\n' "$before" >"$KB_PREVIOUS"

  info "Switching the keyboard from \"$before\" to \"${wanted[*]}\""
  if [[ -f $TYPING_SETUP ]]; then
    error=$(apply_layouts "${wanted[@]}" 2>&1 >/dev/null) || true
  else
    error="$TYPING_SETUP not found"
  fi
  [[ $(current_layouts) == "${wanted[*]}" ]] && return 0

  [[ -z $error ]] || warn "$(tail -n 1 <<<"$error")"
  warn "Couldn't switch the keyboard automatically. Opening Omarchy's picker: check"
  warn "\"Spanish (Latin American)\" and uncheck \"English (US)\"."
  setsid -f omarchy-setup-keyboard >/dev/null 2>&1 ||
    warn "Open it yourself: SUPER + K > Setup > Typing > Keyboard Layouts."
}

# Lives in Omarchy's toggles because those load after bindings.lua/input.lua, and
# alphabetically it lands after zz-try-omarchy.lua, which is what sets applealu_iso.
install_keyboard_model() {
  [[ -n $KB_LAYOUT ]] || return 0
  mkdir -p "$(dirname "$KB_MODEL_FILE")"
  cp "$KB_MODEL_SRC" "$KB_MODEL_FILE"
  hyprctl reload >/dev/null
  info "Keyboard model: $(hyprctl -j getoption input:kb_model | jq -r .str) (instead of Try Omarchy's Mac model)"
}

# Thunar follows the theme colors: Omarchy renders the template into
# ~/.local/state/omarchy/current/theme/thunar.css on every theme change, and the
# GTK3 gtk.css imports it. Omarchy only touches the GTK4 gtk.css.
install_thunar() {
  if ! pacman -Q thunar tumbler >/dev/null 2>&1; then
    info "Installing Thunar (it will ask for your password)"
    omarchy pkg add thunar tumbler || { warn "Couldn't install Thunar; keeping Nautilus."; return 0; }
  fi
  mkdir -p "$(dirname "$THUNAR_TPL")" "$(dirname "$GTK3_CSS")"
  cp "$THUNAR_TPL_SRC" "$THUNAR_TPL"
  printf '@import url("file://%s/.local/state/omarchy/current/theme/thunar.css");\n' "$HOME" >"$GTK3_CSS"
  xdg-mime default thunar.desktop inode/directory
  omarchy theme set "$(omarchy theme current)" >/dev/null 2>&1 || true
  info "File manager: Thunar with the theme colors"
}

set_wallpaper() {
  [[ -n $WALLPAPER ]] || return 0
  [[ -f $WALLPAPER ]] || { info "No wallpaper at $WALLPAPER, leaving the current one"; return 0; }

  local theme dir
  theme=$(omarchy theme current | tr '[:upper:] ' '[:lower:]-')
  dir="$HOME/.config/omarchy/backgrounds/$theme"
  mkdir -p "$dir"
  cp "$WALLPAPER" "$dir/"
  omarchy theme bg set "$dir/$(basename "$WALLPAPER")" >/dev/null
  info "Wallpaper: $(basename "$WALLPAPER") (theme $theme)"
}

restore_keyboard() {
  [[ -f $KB_PREVIOUS ]] || return 0

  local -a previous=()
  read -r -a previous <"$KB_PREVIOUS" || true
  if (( ${#previous[@]} )); then
    apply_layouts "${previous[@]}" >/dev/null 2>&1 || true
    if [[ $(current_layouts) != "${previous[*]}" ]]; then
      warn "Couldn't switch the keyboard back to \"${previous[*]}\"."
      warn "Change it in SUPER + K > Setup > Typing > Keyboard Layouts."
      return 0
    fi
    info "Keyboard back to ${previous[*]}"
  fi
  rm -f "$KB_PREVIOUS"
}

uninstall() {
  rm -f "$BIN_DIR/rectangle" "$BIN_DIR/obsidian-menu" "$KB_MODEL_FILE" "$THUNAR_TPL" "$GTK3_CSS"
  xdg-mime default org.gnome.Nautilus.desktop inode/directory 2>/dev/null || true
  if [[ -f $BINDINGS ]] && grep -qxF -- "$MARK_BEGIN" "$BINDINGS"; then
    strip_block "$BINDINGS" >"$BINDINGS.tmp" && mv "$BINDINGS.tmp" "$BINDINGS"
  fi
  hyprctl reload >/dev/null 2>&1 || true
  restore_keyboard
  info "Done: bindings and helper scripts removed."
}

main() {
  case "${1:-}" in
    --dry-run)
      lua_block
      [[ -z $KB_LAYOUT ]] || printf '\n(It would also set the keyboard to: %s)\n' "$KB_LAYOUT" >&2
      exit 0
      ;;
    --uninstall | "") ;;
    *) die "unknown option: $1 (use --dry-run or --uninstall)" ;;
  esac

  [[ $(uname -s) == Linux ]] || die "Run this script inside Omarchy, not on the Mac."
  command -v hyprctl >/dev/null || die "hyprctl not found: are you in Omarchy/Hyprland?"
  command -v jq >/dev/null || die "jq is missing (sudo pacman -S jq)."

  if [[ ${1:-} == --uninstall ]]; then
    uninstall
    exit 0
  fi

  [[ -f $BINDINGS ]] || die "$BINDINGS doesn't exist. This is for Omarchy 4 (Lua configuration)."
  command -v omarchy-menu-select >/dev/null || warn "omarchy-menu-select not found; the Obsidian menus won't work."

  mkdir -p "$BIN_DIR"

  info "Installing $BIN_DIR/rectangle"
  install_rectangle

  info "Installing $BIN_DIR/obsidian-menu (vault: $VAULT)"
  install_obsidian_menu

  install_bindings
  setup_keyboard
  install_keyboard_model
  install_thunar
  set_wallpaper

  if [[ ! -d $VAULT ]]; then
    warn "The vault doesn't exist yet at $VAULT."
    warn "Sync it (omarchy-install-service-dropbox, for example) or run again with VAULT=/other/path."
  fi
  command -v obsidian >/dev/null || warn "Obsidian isn't installed (omarchy-pkg-add obsidian)."

  local layouts altgr=""
  layouts=$(current_layouts)
  [[ $layouts != latam* ]] || altgr=" (right Option acts as AltGr: @ = right Option + Q)"

  cat <<EOF

Done. Your shortcuts in Omarchy (⌘ = SUPER, ⌥ = ALT, ⌃ = CTRL):
  ${WIN_MODS} + ← → ↑ ↓     halves
  ${WIN_MODS} + Enter       maximize
  ${WIN_MODS} + N / Delete  first / last third (Delete on a MacBook: fn + ⌫)
  ${WIN_MODS} + Insert / M  first / last two thirds (Insert: external keyboard only)
  SUPER + T                   put the window back into the tiling
  SUPER + SPACE               Apps (was Alfred) · Omarchy menu: SUPER + K
  SUPER + SHIFT + K           keybindings list
  SUPER + SHIFT + F           files (Thunar)
  CTRL + V                    clipboard history (was Alfred) · paste: SUPER + V
  SUPER + ALT + O             find an Obsidian note · full menu: SUPER + SHIFT + ALT + O
  Keyboard                    ${layouts}${altgr}

Note: these replace Omarchy's shortcuts for swapping windows (SUPER+SHIFT+arrows),
editor (SUPER+SHIFT+N), music (SUPER+SHIFT+M) and the second browser shortcut
(SUPER+SHIFT+Enter); the browser stays on SUPER+SHIFT+B.
EOF
}

main "$@"
